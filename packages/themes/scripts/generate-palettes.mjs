/**
 * Tailwind-palette quantization (specs/theming.md, plan 2026-09-02):
 * every default `--color-*` token remapped to the theme system's
 * palette — nearest color in OKLAB for color systems, lightness steps
 * for monochrome phosphors. Output: themes/<name>.palette.css,
 * committed. Utilities compile to var(--color-*) in Tailwind v4, so
 * these scoped overrides re-theme every utility inside a host.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const require = createRequire(import.meta.url);
const root = new URL("..", import.meta.url).pathname;

/* --- Color math (sRGB ↔ OKLAB / OKLCH) --- */
const linearize = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const srgbToOklab = (r, g, b) => {
  const [lr, lg, lb] = [linearize(r), linearize(g), linearize(b)];
  const l = Math.cbrt(0.4122214708 * lr + 0.5363325363 * lg + 0.0514459929 * lb);
  const m = Math.cbrt(0.2119034982 * lr + 0.6806995451 * lg + 0.1073969566 * lb);
  const s = Math.cbrt(0.0883024619 * lr + 0.2817188376 * lg + 0.6299787005 * lb);
  return {
    L: 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    a: 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    b: 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  };
};
const hexToOklab = (hex) => {
  const n = hex.replace("#", "");
  const v = n.length === 3 ? [...n].map((c) => c + c).join("") : n;
  return srgbToOklab(
    parseInt(v.slice(0, 2), 16) / 255,
    parseInt(v.slice(2, 4), 16) / 255,
    parseInt(v.slice(4, 6), 16) / 255,
  );
};
const parseColor = (value) => {
  const v = value.trim();
  if (v.startsWith("#")) return hexToOklab(v);
  const oklch = /^oklch\(\s*([\d.]+)%?\s+([\d.]+)\s+([\d.]+)/.exec(v);
  if (oklch) {
    let L = parseFloat(oklch[1]);
    if (v.includes("%")) L /= 100;
    const C = parseFloat(oklch[2]);
    const H = (parseFloat(oklch[3]) * Math.PI) / 180;
    return { L, a: C * Math.cos(H), b: C * Math.sin(H) };
  }
  if (v === "white") return hexToOklab("#ffffff");
  if (v === "black") return hexToOklab("#000000");
  return null; // transparent, currentColor, non-color tokens
};
const dist = (p, q) => (p.L - q.L) ** 2 + (p.a - q.a) ** 2 + (p.b - q.b) ** 2;

/* --- System palettes --- */
