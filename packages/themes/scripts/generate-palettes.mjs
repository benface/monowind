const GREEN = ["#000000", "#003B00", "#00711D", "#00A83C", "#0ADB53", "#66FF84", "#C4FFD1"];
const AMBER = ["#000000", "#4A2D00", "#7A4A00", "#B87400", "#FFB000", "#FFD24A", "#FFEFB3"];
const PAPER = ["#20201C", "#4A473E", "#7A766A", "#B0AB9C", "#DAD5C6", "#F5F1E6"];

const THEMES = {
  bbs: { palette: VGA },
  dos: { palette: VGA },
  "dos-blue": { palette: VGA },
  c64: { palette: C64 },
  "green-phosphor": { palette: GREEN, mono: true },
  amber: { palette: AMBER, mono: true },
  teletype: { palette: PAPER, mono: true },
};

/* --- Tailwind default palette --- */
const themeCss = readFileSync(
  join(require.resolve("tailwindcss/package.json"), "../theme.css"),
  "utf8",
);
const tokens = [];
for (const [, name, value] of themeCss.matchAll(/--color-([\w-]+):\s*([^;]+);/g)) {
  const lab = parseColor(value);
  if (lab) tokens.push({ name, lab });
}
if (tokens.length < 200) throw new Error(`suspiciously few color tokens parsed (${tokens.length})`);

/** theme name → generated palette css. */
export function generatePalettes() {
  const out = new Map();
  for (const [theme, config] of Object.entries(THEMES)) {
    const palette = config.palette.map((hex) => ({ hex, lab: hexToOklab(hex) }));
    const lines = tokens.map(({ name, lab }) => {
      const nearest = config.mono
        ? // Monochrome: map by lightness alone — hue is the phosphor's.
          palette.reduce((a, b) => (Math.abs(b.lab.L - lab.L) < Math.abs(a.lab.L - lab.L) ? b : a))
        : palette.reduce((a, b) => (dist(b.lab, lab) < dist(a.lab, lab) ? b : a));
      return `  --color-${name}: ${nearest.hex.toLowerCase()};`;
    });
    out.set(
      theme,
      `/* Generated by scripts/generate-palettes.mjs — do not edit.
 * Every Tailwind color token quantized to the ${theme} system palette
 * (scoped: only themed hosts re-map; the page keeps stock colors). */
mono-wind.theme-${theme},
.theme-${theme} mono-wind {
${lines.join("\n")}
}
`,
    );
  }
  return out;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  for (const [theme, css] of generatePalettes()) {
    writeFileSync(join(root, "themes", `${theme}.palette.css`), css);
  }
  console.log(`generated ${Object.keys(THEMES).length} palettes from ${tokens.length} tokens`);
}
